package com.foodies.freshmeal.authentication.dto;

import com.foodies.freshmeal.common.constants.RoleType;
import com.foodies.freshmeal.common.valueObject.EmailAddress;
import com.foodies.freshmeal.common.valueObject.PhoneNumber;

import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * ============================================================================
 * DTO : PendingRegistrationCreationInput
 * ============================================================================
 *
 * <p>
 * Carries the registration information required to create a temporary
 * pending registration.
 * </p>
 *
 * <p>
 * This is an internal service input DTO and is not exposed as a public
 * registration API request.
 * </p>
 *
 * <p>
 * The registration number and expiration timestamp are generated by
 * PendingRegistrationServiceImpl.
 * </p>
 *
 * <p>
 * The encoded password must be supplied. Plain-text passwords must never
 * be passed to or persisted by the pending registration service.
 * </p>
 *
 * @author Pankaj Kumar
 * @since 2.0
 */
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class PendingRegistrationCreationInput {

    /**
     * Requested username.
     */
    private String username;

    /**
     * Registrant's first name.
     */
    private String firstName;

    /**
     * Registrant's last name.
     */
    private String lastName;

    /**
     * Normalized email address.
     */
    private EmailAddress email;

    /**
     * Registrant's phone number.
     */
    private PhoneNumber phoneNumber;

    /**
     * Encoded password.
     */
    private String encodedPassword;

    /**
     * Public role requested during registration.
     */
    private RoleType requestedRole;

}